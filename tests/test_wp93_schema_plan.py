def _call(routine, **args):
    raw = {k: (v if isinstance(v, str) and v.startswith("wwv_flow") else repr(v)) for k, v in args.items()}
    parsed = {k: ({"expression": v} if isinstance(v, str) and v.startswith("wwv_flow") else v) for k, v in args.items()}
    return {"routine": routine, "arguments": parsed, "raw_arguments": raw}


def test_apex_references_validate_tables_columns_and_package_members():
    calls = {"pages/page_00010.sql": [
        _call("create_page", p_id=10),
        _call("create_page_plug", p_id="wwv_flow_imp.id(1)", p_plug_name="Form", p_query_type="TABLE", p_query_table="T"),
        _call("create_page_item", p_item_source_plug_id="wwv_flow_imp.id(1)", p_source="NAME"),
        _call("create_page_item", p_item_source_plug_id="wwv_flow_imp.id(1)", p_source="MISSING"),
        _call("create_page_plug", p_id="wwv_flow_imp.id(2)", p_plug_name="Report", p_query_type="SQL",
              p_plug_source="wwv_flow_string.join(wwv_flow_t_varchar2('select id, name', '  from t_v'))"),
        _call("create_page_process", p_process_name="Run", p_process_sql_clob="begin p_pkg.go(:P10_ID); p_pkg.nope; end;"),
    ]}
    refs = collect_apex_references(calls)
    assert {r["kind"] for r in refs} == {"FORM_TABLE", "SQL", "PLSQL_CALL"}
    plan = _plan("create table t (id number(9), name varchar2(10));\n"
                 "create view t_v as select id, name from t;\n"
                 "create or replace package p_pkg as procedure go(p number); end;\n/\n", apex_references=refs)
    failures = _check(plan, "DEP-012")["failures"]
    assert any("T.MISSING not found" in f for f in failures)
    assert any("P_PKG.NOPE not declared" in f for f in failures)
    assert not any("T_V" in f for f in failures)
