DISPOSITIONS = {"AUTOMATIC", "ASSISTED", "MANUAL", "UNSUPPORTED"}


def _plan(sql, **kw):
    return build_schema_plan(sql, source_name="test.sql", **kw)


def _check(plan, check_id):
    return next(c for c in plan["checks"] if c["id"] == check_id)


def _obj(plan, kind, name):
    return next(o for o in plan["objects"] if o["type"] == kind and o["name"] == name)


def _table(plan, name):
    return next(t for t in plan["tables"] if t["name"] == name)


# ----------------------------------------------------------------- identity / generated / defaults


def test_identity_on_null_maps_to_bigint_identity_with_explicit_differences():
    plan = _plan("create table t (id number generated by default on null as identity, "
                 "constraint t_pk primary key (id));")
    assert "id bigint GENERATED BY DEFAULT AS IDENTITY," in plan["sql"]
    ident = _obj(plan, "IDENTITY", "T.ID")
    assert ident["disposition"] == "ASSISTED" and {"SCH005", "SCH006"} <= set(ident["findingCodes"])
    assert plan["expectedCatalog"]["tables"]["t"]["columns"][0]["identity"] == "d"
    assert "setval(pg_get_serial_sequence('app.t', 'id')" in plan["postLoadSql"]


def test_dbms_metadata_identity_options_are_mapped_or_recorded():
    plan = _plan(FIXTURE.read_text())
