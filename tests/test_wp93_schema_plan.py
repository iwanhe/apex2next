TRIGGER_SQL = """
create table p (id number(9) primary key, status varchar2(10));
create table c (id number(9) primary key, p_id number(9), code varchar2(10), created_by varchar2(30), created_on date);
create or replace package audit_pkg as function who return varchar2; end audit_pkg;
/
create or replace trigger c_trg before insert or update on c for each row
declare e_mut exception; pragma exception_init(e_mut, -4091);
begin
  :new.code := upper(:new.code);
  if inserting then
    :new.created_by := audit_pkg.who;
    :new.created_on := sysdate;
  end if;
  select status into l from p where id = :new.p_id;
  if l <> 'DRAFT' then raise_application_error(-20001, 'locked'); end if;
  :new.ghost := 1;
end;
/
"""


def test_trigger_behavior_inventory_and_column_validation():
    plan = _plan(TRIGGER_SQL)
    trg = plan["triggers"][0]
    assert trg["timing"] == "BEFORE" and [e["event"] for e in trg["events"]] == ["INSERT", "UPDATE"]
    assert trg["columnsWritten"]["CODE"][0]["classification"] == "normalization"
    assert trg["columnsWritten"]["CREATED_BY"][0] == {"expression": "audit_pkg.who", "classification": "audit-principal", "branch": "INSERTING"}
    assert trg["columnsWritten"]["CREATED_ON"][0]["classification"] == "audit-clock"
    assert trg["errors"][0]["code"] == -20001
    assert trg["tablesRead"] == ["P"] and trg["mutatingTableHandler"] is True
    assert _obj(plan, "TRIGGER", "C_TRG")["disposition"] == "MANUAL"
    assert any("GHOST" in f for f in _check(plan, "DEP-006")["failures"])
    assert any("AUDIT_PKG.WHO" in f for f in _check(plan, "DEP-007")["failures"]) is False


