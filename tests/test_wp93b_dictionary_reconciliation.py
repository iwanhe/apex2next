def _csv(rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(["SECTION", "OBJ", "ITEM", "C1", "C2", "C3", "C4", "C5"])
    w.writerows(rows)
    return buf.getvalue()


def _reconcile(rows):
    plan = json.loads(json.dumps(build_schema_plan(SOURCE, source_name="t.sql")))
    return reconcile(plan, parse_workshop_csv(_csv(rows)), SOURCE)


def _status(rec):
    return {c["id"]: c["status"] for c in rec["checks"]}


def test_matching_dictionary_reconciles():
    rec = _reconcile(_rows())
    assert rec["summary"]["reconciled"] is True, [c for c in rec["checks"] if c["failures"]]
    assert rec["drift"] == []


def _mutate(rows, section, item, col, value):
    out = [list(r) for r in rows]
    for r in out:
        if r[0] == section and r[2] == item:
            r[col] = value
    return out


@pytest.mark.parametrize("mutation, failing", [
    (("COLUMN", "CODE", 4, "20,,,B,20"), "REC-002"),
    (("COLUMN", "P_ID", 5, "N/NO/NO/NO"), "REC-002"),
    (("IDENTITY", "ID", 3, "ALWAYS"), "REC-003"),
    (("CONSTRAINT", "P_CK", 7, "code in ('A', 'B', 'C')"), "REC-004"),
    (("CONSTRAINT", "C_FK", 6, "NO ACTION"), "REC-004"),
    (("OBJECT", "V", 3, "INVALID"), "REC-001"),
    (("TRIGGER", "C_TRG", 5, "DISABLED"), "REC-006"),
    (("SOURCE_LINES", "C_TRG", 4, "999"), "REC-008"),
])
def test_each_kind_of_drift_is_detected(mutation, failing):
    section, item, col, value = mutation
    rec = _reconcile(_mutate(_rows(), section, item, col, value))
    assert _status(rec)[failing] == "FAIL"


def test_view_redefinition_after_install_is_reported_as_drift():
    rows = [r for r in _rows() if not (r[0] == "COLUMN" and r[1] == "V")]
    rows += [["COLUMN", "V", "LABEL", "VARCHAR2", "10,,,B,10", "Y/NO/NO/NO", "", "1"]]
    rows = _mutate(rows, "OBJECT", "V", 5, "2026-02-01T00:00:00")
    rows.append(["DEPENDENCY", "VIEW", "V", "TABLE", "S.C", "HARD", "", ""])
    rec = _reconcile(rows)
    s = _status(rec)
    assert s["REC-007"] == s["REC-009"] == s["REC-011"] == "FAIL"
    assert rec["drift"][0]["object"] == "VIEW V" and rec["drift"][0]["kind"] == "definition"


def test_missing_and_unexplained_objects():
    rows = [r for r in _rows() if not (r[0] == "OBJECT" and r[2] == "C_N1")]
    rows.append(["OBJECT", "TABLE", "Q", "VALID", TS, TS, "N", ""])
    failures = next(c for c in _reconcile(rows)["checks"] if c["id"] == "REC-001")["failures"]
    assert "INDEX C_N1" in failures and "unexplained: TABLE Q" in failures


