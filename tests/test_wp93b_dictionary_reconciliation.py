def test_view_texts_verify_recompiled_views_and_detect_text_drift():
    rows = _mutate(_rows(), "OBJECT", "V", 5, "2026-02-01T00:00:00")
    plan = json.loads(json.dumps(build_schema_plan(SOURCE, source_name="t.sql")))
    same = reconcile(plan, parse_workshop_csv(_csv(rows)), SOURCE,
                     view_texts={"V": {"length": 22, "text": "select id, code from p"}})
    assert same["summary"]["reconciled"] is True and same["resolutions"][0]["object"] == "VIEW V"
    changed = reconcile(plan, parse_workshop_csv(_csv(rows)), SOURCE,
                        view_texts={"V": {"length": 25, "text": "select id, code from p p2"}})
    assert _status(changed)["REC-012"] == "FAIL" and _status(changed)["REC-011"] == "FAIL"
    truncated = reconcile(plan, parse_workshop_csv(_csv(_rows())), SOURCE,
                          view_texts={"V": {"length": 4000, "text": "select id, code from p"}})
    assert "truncated" in next(c for c in truncated["checks"] if c["id"] == "REC-012")["failures"][0]


def test_override_replaces_stale_view_and_is_recorded():
    ov = {"format": "apex2next.dictionary-overrides.v1", "evidence": [],
          "overrides": [view_override("V", "select id, code, 1 extra from p", reason="drift", last_ddl=TS)]}
    effective, records = apply_overrides(SOURCE, ov)
    assert "1 extra from p" in effective and "select id, code from p;" not in effective
    assert records[0]["action"] == "replaced"
    plan = build_schema_plan(SOURCE, source_name="t.sql", overrides=ov)
    assert plan["source"]["sha256"] != plan["effectiveSource"]["sha256"]
    assert next(v for v in plan["views"] if v["name"] == "V")["outputColumns"] == ["ID", "CODE", "EXTRA"]
    assert next(o for o in plan["objects"] if o["name"] == "V")["definitionSource"] == "dictionary override"


def test_override_for_missing_object_is_appended_and_bad_overrides_are_rejected():
    ov = {"format": "apex2next.dictionary-overrides.v1", "evidence": [],
          "overrides": [view_override("W", "select id from c", reason="only installed", last_ddl=None)]}
    effective, records = apply_overrides(SOURCE, ov)
    assert records[0]["action"] == "appended" and effective.rstrip().endswith("select id from c;")
    bad = {"format": "apex2next.dictionary-overrides.v1", "evidence": [],
           "overrides": [{"object": "VIEW", "name": "V", "ddl": "create or replace view other as select 1 x from dual"}]}
    with pytest.raises(ValueError):
        apply_overrides(SOURCE, bad)
    with pytest.raises(ValueError):
        view_override("V", "delete from p", reason="x", last_ddl=None)


def test_dictionary_dependency_explained_transitively_passes():
    src = SOURCE + "create or replace view v2 as select id from v;\n"
    rows = _rows() + [["OBJECT", "VIEW", "V2", "VALID", TS, TS, "N", ""],
                      ["COLUMN", "V2", "ID", "NUMBER", "22,,,,0", "N/NO/NO/NO", "", "1"],
                      ["DEPENDENCY", "VIEW", "V2", "VIEW", "S.V", "HARD", "", ""],
                      ["DEPENDENCY", "VIEW", "V2", "TABLE", "S.P", "HARD", "", ""]]
    plan = json.loads(json.dumps(build_schema_plan(src, source_name="t.sql")))
    rec = reconcile(plan, parse_workshop_csv(_csv(rows)), src)
    dep = next(c for c in rec["checks"] if c["id"] == "REC-009")
    assert dep["status"] == "PASS" and any("V2 -> P" in n for n in dep["notes"])


