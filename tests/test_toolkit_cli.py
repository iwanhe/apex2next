"""The single-entry toolkit CLI (tools/apex2next) wraps the existing tools and summarizes their results."""
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CLI = ROOT / "tools" / "apex2next"


def run(*args, cwd=ROOT):
    return subprocess.run([sys.executable, str(CLI), *map(str, args)], cwd=cwd, capture_output=True, text=True)


def test_help_lists_every_command():
    r = run("-h")
    assert r.returncode == 0
    for cmd in ("doctor", "queries", "inventory", "schema-plan", "dictionary-check", "plsql", "load-data", "catalog",
                "generate", "assess", "supporting-objects", "new", "smoke", "scoreboard"):
        assert cmd in r.stdout


def test_queries_are_copied(tmp_path):
    r = run("queries", "--out", tmp_path)
    assert r.returncode == 0, r.stderr
    assert (tmp_path / "dictionary_inventory_apex_workshop.sql").read_text().strip()


def test_inventory_on_synthetic_export(tmp_path):
    r = run("inventory", ROOT / "tests/fixtures/wp9.5/synthetic-export", "--out", tmp_path)
    assert r.returncode == 0, r.stderr
    inv = json.loads((tmp_path / "apex-page-inventory.json").read_text())
    assert f"{len(inv['pages'])} pages" in r.stdout


def test_schema_plan_and_plsql_on_small_script(tmp_path):
    ddl = tmp_path / "install.sql"
    ddl.write_text("create table t (id number generated by default on null as identity, name varchar2(30) not null,\n"
                   "  constraint t_pk primary key (id));\n"
                   "create or replace view t_v as select id, nvl(name, '-') name from t;\n", encoding="utf-8")
    r = run("schema-plan", ddl, "--out", tmp_path / "plan")
    assert r.returncode == 0, r.stderr + r.stdout
    assert "Tables 1/1, views 1/1" in r.stdout
    assert "create table" in (tmp_path / "plan" / "0001_schema.sql").read_text().lower()
    assert (tmp_path / "plan" / "schema-conversion-report.md").exists()
    assert "RuntimeWarning" not in r.stderr

    body = tmp_path / "pkg.sql"
    body.write_text("create or replace procedure p is begin update t set name = nvl(name, 'x'); end;\n/\n", encoding="utf-8")
    r = run("plsql", body, "--out", tmp_path / "plsql")
    assert r.returncode in (0, 2), r.stderr
    assert "Statements: update 1" in r.stdout


def test_new_application_flow_inventory_plan_generate(tmp_path):
    """R3: export + DDL -> application directory -> proposed map -> generated sources, report and snapshot query."""
    app = tmp_path / "app"
    assert run("inventory", ROOT / "tests/fixtures/wp9.5/synthetic-export", "--out", app / "ui").returncode == 0
    ddl = tmp_path / "install.sql"
    ddl.write_text("create table things (id number generated by default on null as identity, name varchar2(30) not null,\n"
                   "  constraint things_pk primary key (id));\n", encoding="utf-8")
    assert run("schema-plan", ddl, "--out", app / "db").returncode == 0
    r = run("generate", app)
    assert r.returncode != 0 and "--init-map" in r.stderr  # the reviewed map comes first
    assert run("generate", app, "--init-map").returncode == 0
    assert run("generate", app, "--init-map").returncode != 0, "a reviewed map is never overwritten"
    r = run("generate", app)
    assert r.returncode == 0, r.stderr
    assert "0 generated" in r.stdout and "1 to write by hand" in r.stdout  # one page mixing a report and a form
    sources = (app / "apps/api/src/pages/app-sources.generated.ts").read_text()
    assert "sql: 'select name d, id r from app.things'," in sources and "numeric" not in sources
    report = json.loads((app / "ui/generation-report.json").read_text())
    assert report["summary"]["lovs"] == {"GENERATED": 1, "PROVIDED": 1}
    region = next(x for x in report["regions"] if x["region"] == "Report")
    assert region["status"] == "MANUAL" and "GEN014" in region["findings"]  # the export defines no IR column for ID
    assert run("generate", app, "--check").returncode == 0
    (app / "apps/web/lib/app-routes.generated.ts").write_text("// edited\n")
    r = run("generate", app, "--check")
    assert r.returncode == 1 and "stale: apps/web/lib/app-routes.generated.ts" in r.stdout
    r = run("queries", "--out", tmp_path / "q", "--plan", app / "db/schema-plan.json", "--title", "Synthetic")
    assert r.returncode == 0, r.stderr
    snapshot = (tmp_path / "q/snapshot_apex_workshop.sql").read_text()
    assert "union all select 'ROW', 'THINGS', to_char(id), json_object(" in snapshot


