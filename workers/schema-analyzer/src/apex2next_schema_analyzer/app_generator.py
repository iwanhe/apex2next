"""R3 application generator: APEX page inventory -> target application sources.

Reads, in one application directory::

    ui/apex-page-inventory.json   pages and components of the APEX export (apex2next inventory)
    db/schema-plan.json           converted schema: known objects, column types, function mappings
    db/target-catalog.json        optional: column types of the migrated PostgreSQL schema (apex2next catalog)
    ui/app-map.json               reviewed names the export does not decide: routes, region keys, form names

and writes the files a developer otherwise types by hand for the common page patterns::

    apps/api/src/pages/app-sources.generated.ts   region sources, LOV sources, form sources (PostgreSQL SQL)
    apps/web/lib/app-routes.generated.ts          page routes, downloadable Interactive Reports
    apps/web/app/(app)/**/page.tsx                Interactive Report, faceted search and form dialog pages
    ui/generation-report.json|md                  what was generated and what is left to do, per page

Nothing is guessed: a query that cannot be translated safely and a page that matches no pattern are listed as
TODO with the reason. Output is deterministic; ``--check`` fails when a generated file is stale.
"""
