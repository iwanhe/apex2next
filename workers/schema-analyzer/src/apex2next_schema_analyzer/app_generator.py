# ------------------------------------------------------------------------------------------- small helpers
def camel(text: str) -> str:
    words = re.findall(r"[A-Za-z0-9]+", text)
    if not words:
        return "x"
    out = words[0].lower() + "".join(w[:1].upper() + w[1:].lower() for w in words[1:])
    return out if not out[0].isdigit() else f"r{out}"


def kebab(text: str) -> str:
    return "-".join(w.lower() for w in re.findall(r"[A-Za-z0-9]+", text)) or "page"


def ts_str(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'").replace("\n", "\\n").replace("\r", "\\r") + "'"


def ts_key(key: str) -> str:
    return key if re.fullmatch(r"[A-Za-z_$][A-Za-z0-9_$]*", key) else ts_str(key)


def ts_list(items: list[str]) -> str:
    return "[" + ", ".join(ts_str(i) for i in items) + "]"


def components(page: dict[str, Any], kind: str) -> list[dict[str, Any]]:
    return [c for c in page["components"] if c["kind"] == kind]


def regions_of(page: dict[str, Any], source_type: str) -> list[dict[str, Any]]:
    return [c for c in components(page, "REGION") if c["props"].get("plug_source_type") == source_type]


def parse_link(url: str | None) -> dict[str, Any] | None:
    """APEX f?p link: f?p=App:Page:Session:Request:Debug:ClearCache:itemNames:itemValues."""
    if not url or not url.startswith("f?p="):
        return None
    parts = url[4:].split(":")
    if len(parts) < 2 or not parts[1].isdigit():
        return None
    names = [n for n in (parts[6].split(",") if len(parts) > 6 else []) if n]
    values = [v.strip("\\") for v in (parts[7].split(",") if len(parts) > 7 else [])]
    return {"page": int(parts[1]), "items": dict(zip(names, values + [""] * (len(names) - len(values))))}


def row_column(value: str) -> str | None:
    """Row column of a link value: #COL# (reports) or &COL. (cards)."""
    m = re.fullmatch(r"#([A-Za-z0-9_$]+)#", value) or re.fullmatch(r"&([A-Za-z0-9_$]+)\.", value)
    return m.group(1).lower() if m else None


def finding(code: str, detail: str | None = None) -> dict[str, Any]:
    disposition, message = GEN_RULES[code]
    out: dict[str, Any] = {"code": code, "disposition": disposition, "message": message}
    if detail:
        out["detail"] = detail
    return out


def column_kind(pg_type: str) -> str:
    t = pg_type.lower()
    if t.startswith(NUMBER_TYPES):
        return "NUMBER"
    if t.startswith(DATE_TYPES):
        return "DATE"
    return "STRING"


# ------------------------------------------------------------------------------------------- inputs
class Inputs:
    def __init__(self, app: Path) -> None:
        self.app = app
        self.inventory = json.loads((app / "ui/apex-page-inventory.json").read_text(encoding="utf-8"))
        self.plan = json.loads((app / "db/schema-plan.json").read_text(encoding="utf-8"))
        catalog_path = app / "db/target-catalog.json"
        self.catalog = json.loads(catalog_path.read_text(encoding="utf-8")) if catalog_path.exists() else None
        self.pages = {p["id"]: p for p in self.inventory["pages"]}
        self.schema = self.plan.get("targetSchema", "app")
        self.known = frozenset([t["name"] for t in self.plan["tables"]] + [v["name"] for v in self.plan["views"]])
        self.mappings = {m["source"].upper(): m["target"] for m in self.plan.get("functionMappings", [])}
        self.types: dict[str, dict[str, str]] = {}
        for t in self.plan["tables"]:
            self.types[t["targetName"]] = {c["targetName"]: c["targetType"] or "text" for c in t["columns"]}
        if self.catalog:
            for name, cols in self.catalog["relations"].items():
                self.types[name] = dict(cols)
        self.numeric = {name.upper(): {c.upper() for c, t in cols.items() if column_kind(t) == "NUMBER"}
                        for name, cols in self.types.items()}
        # tables whose source triggers are not converted: native form DML would skip their logic
        self.triggered = {t["table"].upper() for t in self.plan.get("triggers", []) if not t.get("emit")}

    def translate(self, sql: str, source_schemas: list[str]):
        return translate_query(sql, known_objects=self.known, source_schemas=frozenset(s.upper() for s in source_schemas),
                               function_mappings=self.mappings, target_schema=self.schema)


# ------------------------------------------------------------------------------------------- page patterns
def form_region(page: dict[str, Any]) -> dict[str, Any] | None:
    forms = regions_of(page, "NATIVE_FORM")
    return forms[0] if len(forms) == 1 else None


def primary_key_item(page: dict[str, Any]) -> dict[str, Any] | None:
    keys = [i for i in components(page, "ITEM") if i["props"].get("is_primary_key") is True]
    return keys[0] if len(keys) == 1 else None


def classify(page: dict[str, Any]) -> tuple[str, str | None]:
    """Pattern of a page and, for MANUAL, the reason."""
    if page["id"] == 0:
        return "GLOBAL", None
    names = {i["name"].split("_", 1)[-1] for i in components(page, "ITEM")}
    if (page.get("alias") or "").upper() == "LOGIN" or {"USERNAME", "PASSWORD"} <= names:
        return "LOGIN", None
    regions = components(page, "REGION")
    typed = sorted({r["props"].get("plug_source_type") for r in regions} - CONTAINER_TYPES)
    reports = components(page, "REPORT_REGION")
    if typed == ["NATIVE_IR"] and len(regions_of(page, "NATIVE_IR")) == 1 and not reports and not components(page, "ITEM"):
        return "IR_PAGE", None
    if typed == ["NATIVE_FACETED_SEARCH"] and len(reports) == 1:
        return "FACETED_REPORT", None
    if typed == ["NATIVE_CARDS", "NATIVE_FACETED_SEARCH"] and len(regions_of(page, "NATIVE_CARDS")) == 1 and not reports:
        return "FACETED_CARDS", None
    if typed == ["NATIVE_FORM"] and form_region(page) is not None and not reports and primary_key_item(page) is not None:
        return "FORM_DIALOG", None
    types = {r["props"].get("plug_source_type") for r in regions}
    inputs = [i["name"] for i in components(page, "ITEM") if i["props"].get("display_as") != "NATIVE_HIDDEN"]
    if types <= COMPOSE_TYPES and not inputs and len(regions_of(page, "NATIVE_IR")) <= 1:
        return "COMPOSED", None
    shape = typed + ([f"{len(reports)} classic report(s)"] if reports else [])
    if types <= COMPOSE_TYPES and inputs:
        return "MANUAL", "input items: " + ", ".join(inputs[:4]) + (" ..." if len(inputs) > 4 else "")
    return "MANUAL", "regions: " + (", ".join(shape) if shape else "none")


