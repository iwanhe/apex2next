def finding(code: str, *, obj: str | None = None, line: int | None = None,
            detail: str | None = None, disposition: str | None = None,
            message: str | None = None) -> dict[str, Any]:
    if code in SCHEMA_RULES:
        default_disp, default_msg = SCHEMA_RULES[code]
    else:  # expression rules carry their own disposition/message
        default_disp, default_msg = disposition or "MANUAL", message or code
    out: dict[str, Any] = {"code": code, "disposition": disposition or default_disp,
                           "message": message or default_msg}
    if obj is not None:
        out["object"] = obj
    if line is not None:
        out["line"] = line
    if detail:
        out["detail"] = detail
    return out


def worst(findings: list[dict[str, Any]]) -> str:
    result = "AUTOMATIC"
    for f in findings:
        if DISPOSITION_RANK[f["disposition"]] > DISPOSITION_RANK[result]:
            result = f["disposition"]
    return result


def target_name(name: str, max_bytes: int = 63) -> str:
    lowered = name.lower()
    if len(lowered.encode("utf-8")) <= max_bytes:
        return lowered
    digest = hashlib.sha256(lowered.encode("utf-8")).hexdigest()[:8]
    return lowered.encode("utf-8")[: max_bytes - 9].decode("utf-8", "ignore") + "_" + digest


def catalog_type(target: str) -> str:
    """Translate an emitted type to PostgreSQL ``format_type()`` spelling."""
    m = re.fullmatch(r"varchar\((\d+)\)", target)
    if m:
        return f"character varying({m.group(1)})"
    m = re.fullmatch(r"char\((\d+)\)", target)
    if m:
        return f"character({m.group(1)})"
    m = re.fullmatch(r"timestamptz\((\d)\)", target)
    if m:
        return f"timestamp({m.group(1)}) with time zone"
    return target


# --------------------------------------------------------------------------- helpers


class Cursor:
    """Cursor over significant tokens of a statement."""

    def __init__(self, tokens: list[Token]):
        self.all = tokens
        self.sig = significant(tokens)
        self.i = 0

    def peek(self, offset: int = 0) -> Token | None:
        j = self.i + offset
        return self.sig[j] if 0 <= j < len(self.sig) else None

    def word(self, offset: int = 0) -> str | None:
        t = self.peek(offset)
        return t.upper if t is not None and t.kind == "IDENT" else None

    def is_op(self, text: str, offset: int = 0) -> bool:
        t = self.peek(offset)
        return t is not None and t.kind == "OP" and t.text == text

    def take(self) -> Token:
        t = self.sig[self.i]
        self.i += 1
        return t

    def accept(self, *words: str) -> bool:
        for j, w in enumerate(words):
            if self.word(j) != w:
                return False
        self.i += len(words)
        return True

    def done(self) -> bool:
        return self.i >= len(self.sig)

    def paren_group(self) -> list[Token]:
        """Consume '( ... )' and return the inner tokens *with* whitespace."""
        assert self.is_op("(")
        open_tok = self.peek()
        assert open_tok is not None
        start_all = self.all.index(open_tok)
        end_all = find_matching(self.all, start_all)
        close_tok = self.all[end_all]
        self.i = self.sig.index(close_tok) + 1
        return self.all[start_all + 1:end_all]

    def rest(self) -> list[Token]:
        return self.sig[self.i:]

    def tokens_until(self, stop: frozenset[str]) -> list[Token]:
        """Consume tokens (with whitespace) until a stop word at depth 0."""
        if self.done():
            return []
        first = self.peek()
        assert first is not None
        start_all = self.all.index(first)
        depth = 0
        while not self.done():
            t = self.peek()
            assert t is not None
            if t.kind == "OP" and t.text == "(":
                depth += 1
            elif t.kind == "OP" and t.text == ")":
                depth -= 1
            elif depth == 0 and t.kind == "IDENT" and t.upper in stop:
                break
            self.i += 1
        end_all = self.all.index(self.sig[self.i]) if not self.done() else len(self.all)
        return self.all[start_all:end_all]


def _read_name(cur: Cursor) -> tuple[str | None, str]:
    """Read [owner.]name; return (owner, name) as Oracle names."""
    first = cur.take()
    if cur.is_op("."):
        cur.take()
        second = cur.take()
        return identifier_name(first), identifier_name(second)
    return None, identifier_name(first)


def _column_list(tokens: list[Token]) -> list[str]:
    return [identifier_name(significant(part)[0]) for part in split_top_level(tokens)
            if significant(part)]


