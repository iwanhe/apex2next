def map_type(name: str, args: str, suffix: str) -> tuple[str | None, str, list[str], str | None]:
    """Return (target type, family, rule codes, block reason)."""
    args = re.sub(r"\s+", " ", args.strip())
    suffix = re.sub(r"\s+", " ", suffix.strip().upper())
    if name == "NUMBER" or name in {"NUMERIC", "DECIMAL", "DEC"}:
        if not args:
            return "numeric", "numeric", ["SCH002"], None
        m = re.fullmatch(r"(\*|\d+)(?:\s*,\s*(-?\d+))?", args)
        if not m:
            return None, "numeric", ["SCH001"], f"NUMBER({args}) is not a simple precision/scale."
        precision = 38 if m.group(1) == "*" else int(m.group(1))
        scale = int(m.group(2)) if m.group(2) is not None else 0
        if not 1 <= precision <= 38 or scale < 0 or scale > precision:
            return None, "numeric", ["SCH001"], f"NUMBER({args}) scale/precision is outside the supported subset."
        if scale == 0 and m.group(1) != "*":
            if precision <= 4:
                return "smallint", "integer", ["SCH032"], None
            if precision <= 9:
                return "integer", "integer", ["SCH032"], None
            if precision <= 18:
                return "bigint", "integer", ["SCH032"], None
        return f"numeric({precision},{scale})", "numeric", [], None
    if name in {"INTEGER", "INT", "SMALLINT"}:
        return "numeric(38,0)", "numeric", [], None
    if name in {"VARCHAR2", "VARCHAR", "NVARCHAR2"}:
        m = re.fullmatch(r"(\d+)(?: (BYTE|CHAR))?", args, re.I)
        if not m or not 1 <= int(m.group(1)) <= 32767:
            return None, "text", ["SCH001"], f"{name}({args}) length is not supported."
        return f"varchar({int(m.group(1))})", "text", ["SCH004"], None
    if name in {"CHAR", "NCHAR", "CHARACTER"}:
        m = re.fullmatch(r"(\d+)?(?: ?(BYTE|CHAR))?", args, re.I)
        length = int(m.group(1)) if m and m.group(1) else 1
        if not m or not 1 <= length <= 2000:
            return None, "text", ["SCH001"], f"{name}({args}) length is not supported."
        return f"char({length})", "text", ["SCH004"], None
    if name in {"CLOB", "NCLOB", "LONG"}:
        return "text", "text", ["SCH033"], None
    if name in {"BLOB", "RAW"}:
        return "bytea", "binary", ["SCH033"] if name == "BLOB" else [], None
    if name == "DATE":
        return "timestamp(0) without time zone", "timestamp", ["SCH003"], None
    if name == "TIMESTAMP":
        precision = int(args) if args.isdigit() else 6
        if args and not args.isdigit():
            return None, "timestamp", ["SCH001"], f"TIMESTAMP({args}) precision is not simple."
        if precision > 6:
            return "timestamp(6) without time zone", "timestamp", ["SCH033"], None
        if suffix == "WITH TIME ZONE":
            return f"timestamptz({precision})", "timestamptz", ["SCH033"], None
        if suffix == "WITH LOCAL TIME ZONE":
            return f"timestamptz({precision})", "timestamptz", ["SCH003"], None
        if suffix:
            return None, "timestamp", ["SCH001"], f"TIMESTAMP {suffix} is not supported."
        return f"timestamp({precision}) without time zone", "timestamp", [], None
    if name in {"BINARY_FLOAT"}:
        return "real", "float", ["SCH033"], None
    if name in {"BINARY_DOUBLE", "FLOAT", "DOUBLE"}:
        return "double precision", "float", ["SCH033"], None
    if name == "BOOLEAN":
        return "boolean", "boolean", [], None
    if name == "INTERVAL":
        return "interval", "interval", ["SCH033"], None
    if name == "JSON":
        return "jsonb", "json", ["SCH033"], None
    return None, "unknown", ["SCH001"], f"Datatype {name} is not in the conversion allowlist."


def _read_datatype(cur: Cursor) -> tuple[str, str, str, str]:
    """Return (type name, args, suffix, source text) and advance the cursor."""
    t = cur.take()
    name = t.upper
    parts = [t.text]
    if name == "DOUBLE" and cur.word() == "PRECISION":
        parts.append(cur.take().text)
    if name == "LONG" and cur.word() == "RAW":
        parts.append(cur.take().text)
        name = "RAW"
    if name in {"NATIONAL", "CHARACTER"} and cur.word() in {"CHARACTER", "CHAR", "VARYING"}:
        while cur.word() in {"CHARACTER", "CHAR", "VARYING"}:
            parts.append(cur.take().text)
        name = "VARCHAR2" if "VARYING" in " ".join(parts).upper() else "CHAR"
    args = ""
    if cur.is_op("("):
        inner = cur.paren_group()
        args = render(inner)
        parts.append("(" + args + ")")
    suffix_parts: list[str] = []
    if name == "TIMESTAMP" and cur.word() == "WITH":
        while cur.word() in {"WITH", "LOCAL", "TIME", "ZONE"}:
            suffix_parts.append(cur.take().text)
    if name == "INTERVAL":
        while not cur.done() and (cur.word() in {"YEAR", "MONTH", "DAY", "SECOND", "TO"} or cur.is_op("(")):
            if cur.is_op("("):
                suffix_parts.append("(" + render(cur.paren_group()) + ")")
            else:
                suffix_parts.append(cur.take().text)
    source = " ".join(parts + suffix_parts)
    return name, args, " ".join(suffix_parts), source


