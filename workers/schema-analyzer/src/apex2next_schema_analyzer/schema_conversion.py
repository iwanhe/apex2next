def _expr_findings(result, obj: str, line: int) -> list[dict[str, Any]]:
    return [finding(f["code"], obj=obj, line=line, detail=f.get("detail"),
                    disposition=f["disposition"], message=f["message"]) for f in result.findings]


def parse_column(element: list[Token], table: str, line: int,
                 constraints: list[dict[str, Any]]) -> dict[str, Any]:
    cur = Cursor(element)
    name_tok = cur.take()
    name = identifier_name(name_tok)
    obj = f"{table}.{name}"
    col: dict[str, Any] = {"name": name, "line": line, "nullable": True, "findings": [],
                           "omitted": []}
    if cur.word() in {"AS", "GENERATED"} and not (cur.word() == "GENERATED" and cur.word(1) == "BY"):
        col.update({"sourceType": None, "targetType": None, "typeFamily": None})
    else:
        tname, args, suffix, source = _read_datatype(cur)
        target, family, codes, block = map_type(tname, args, suffix)
        col.update({"sourceType": source, "targetType": target, "typeFamily": family})
        for code in codes:
            if code != "SCH004":
                col["findings"].append(finding(code, obj=obj, line=line, detail=source))
        if "SCH004" in codes:
            col["character"] = True
        if block:
            col["blocked"] = block
    while not cur.done():
        w = cur.word()
        if w == "DEFAULT":
            cur.take()
            on_null = cur.accept("ON", "NULL")
            expr_tokens = cur.tokens_until(STOP_WORDS - {"NULL", "DEFAULT", "AS"})
            if not significant(expr_tokens) and cur.word() == "NULL":
                cur.take()
                expr_tokens = []
            source_text = render(expr_tokens).strip()
            col["default"] = {"source": source_text or "NULL", "onNull": on_null}
            if on_null:
                col["nullable"] = False
                col["findings"].append(finding("SCH014", obj=obj, line=line))
            if not source_text or source_text.upper() == "NULL":
                col["default"]["target"] = None
                continue
            converted = convert_expression(expr_tokens)
            ok = (converted.disposition in {"AUTOMATIC", "ASSISTED"} and not converted.identifiers
                  and not converted.has_subquery)
            if ok:
                col["default"]["target"] = converted.sql.strip()
                if converted.findings:
                    col["findings"].append(finding("SCH011", obj=obj, line=line, detail=source_text))
                    col["findings"].extend(_expr_findings(converted, obj, line))
            else:
                col["default"]["target"] = None
                col["omitted"].append(f"DEFAULT {source_text}")
                col["findings"].append(finding("SCH013", obj=obj, line=line, detail=source_text))
        elif w == "GENERATED" and cur.word(1) in {"ALWAYS", "BY"}:
            cur.take()
            mode = "ALWAYS" if cur.accept("ALWAYS") else ("BY DEFAULT" if cur.accept("BY", "DEFAULT") else None)
            on_null = mode == "BY DEFAULT" and cur.accept("ON", "NULL")
            if cur.accept("AS", "IDENTITY"):
                opt_tokens = cur.paren_group() if cur.is_op("(") else cur.tokens_until(
                    frozenset({"NOT", "CONSTRAINT", "PRIMARY", "UNIQUE", "CHECK", "REFERENCES",
                               "ENABLE", "NULL"}))
                opts, dropped, manual = parse_identity_options(opt_tokens)
                col["identity"] = {"mode": mode, "onNull": on_null, "options": opts,
                                   "droppedOptions": dropped, "manualOptions": manual}
                col["nullable"] = False
                if on_null:
                    col["findings"].append(finding("SCH005", obj=obj, line=line))
                if dropped:
                    col["findings"].append(finding("SCH007", obj=obj, line=line, detail=", ".join(dropped)))
                if manual:
                    col["findings"].append(finding("SCH008", obj=obj, line=line, detail=", ".join(manual)))
                    col["blocked"] = "Identity option without PostgreSQL equivalent: " + ", ".join(manual)
            elif cur.word() == "AS":
                cur.take()
                _virtual_column(cur, col, obj, line)
            else:
                col["blocked"] = "Unrecognized GENERATED clause."
                col["findings"].append(finding("SCH026", obj=obj, line=line, detail="GENERATED"))
        elif w == "AS" and cur.is_op("(", 1):
            cur.take()
            _virtual_column(cur, col, obj, line)
        elif w == "VISIBLE":
            cur.take()
        elif w in {"INVISIBLE", "COLLATE", "ENCRYPT", "SORT"}:
            cur.take()
            col["blocked"] = f"Column option {w} requires target design."
            col["findings"].append(finding("SCH026", obj=obj, line=line, detail=w))
            break
        else:
            item = parse_constraint(cur, column=name, line=line, origin="CREATE TABLE (inline)")
            if item is None:
                bad = cur.take()
                col["blocked"] = f"Unrecognized column element near '{bad.text}'."
                col["findings"].append(finding("SCH026", obj=obj, line=line, detail=bad.text))
                break
            if item["kind"] == "NOT NULL":
                if item.get("enabled", True):
                    col["nullable"] = False
                    if item.get("name"):
                        col["findings"].append(finding("SCH034", obj=obj, line=line, detail=item["name"]))
                else:
                    col["findings"].append(finding("SCH017", obj=obj, line=line, detail="NOT NULL DISABLE"))
                    col["omitted"].append("NOT NULL (DISABLE)")
            elif item["kind"] == "NULL":
                pass
            else:
                constraints.append(item)
    return col


def _virtual_column(cur: Cursor, col: dict[str, Any], obj: str, line: int) -> None:
    expr = cur.paren_group()
    virtual = cur.accept("VIRTUAL")
    col["generated"] = {"source": render(expr).strip(), "virtual": True, "explicitVirtual": virtual,
                        "tokens": expr}


def parse_create_table(stmt: Statement) -> dict[str, Any]:
    cur = Cursor(stmt.tokens)
    temporary = False
    while not cur.done() and cur.word() != "TABLE":
        if cur.word() in {"GLOBAL", "PRIVATE"}:
            temporary = True
        cur.take()
    cur.take()  # TABLE
    owner, name = _read_name(cur)
    table: dict[str, Any] = {"kind": "TABLE", "name": name, "owner": owner, "line": stmt.line,
                             "columns": [], "constraints": [], "findings": [], "comments": {},
                             "statement": stmt.text}
    if temporary:
        table["blocked"] = "GLOBAL/PRIVATE TEMPORARY table requires target design."
        table["findings"].append(finding("SCH020", obj=name, line=stmt.line, detail="TEMPORARY"))
    if not cur.is_op("("):
        table["blocked"] = "CREATE TABLE without a column list (e.g. CTAS) is not converted."
        table["findings"].append(finding("SCH020", obj=name, line=stmt.line, detail="AS SELECT"))
        return table
    body = cur.paren_group()
    for element in split_top_level(body):
        sig = significant(element)
        first = sig[0].upper if sig[0].kind == "IDENT" else None
        elem_line = stmt.line + stmt.text.count("\n", 0, sig[0].offset)
        if first in {"CONSTRAINT", "PRIMARY", "UNIQUE", "CHECK", "FOREIGN"}:
            c = Cursor(element)
            item = parse_constraint(c, column=None, line=elem_line, origin="CREATE TABLE")
            if item is None or not c.done():
                table["findings"].append(finding("SCH026", obj=name, line=elem_line,
                                                 detail=render(element).strip()[:120]))
                table["blocked"] = "Unrecognized table constraint."
                continue
            table["constraints"].append(item)
        elif len(sig) > 1 and ((first == "SUPPLEMENTAL" and sig[1].upper == "LOG")
                               or (first in {"PERIOD", "SCOPE"} and sig[1].upper == "FOR")
                               or (first == "REF" and sig[1].text == "(")):
            table["findings"].append(finding("SCH026", obj=name, line=elem_line, detail=first))
            table["blocked"] = f"Table element {first} is not converted."
        else:
            table["columns"].append(parse_column(element, name, elem_line, table["constraints"]))
    # trailing table options
    rest = cur.rest()
    words = [t.upper for t in rest if t.kind == "IDENT"]
    blocking = [w for w in words if w in BLOCKING_TABLE_OPTIONS]
    if blocking:
        table["blocked"] = "Table option requires target design: " + ", ".join(sorted(set(blocking)))
        table["findings"].append(finding("SCH020", obj=name, line=stmt.line, detail=", ".join(sorted(set(blocking)))))
    elif rest:
        table["findings"].append(finding("SCH019", obj=name, line=stmt.line,
                                         detail=" ".join(t.text for t in rest)[:200]))
    return table


def parse_alter_table(stmt: Statement) -> dict[str, Any]:
    cur = Cursor(stmt.tokens)
    cur.i = 2  # ALTER TABLE
    owner, name = _read_name(cur)
    result: dict[str, Any] = {"kind": "ALTER_TABLE", "table": name, "owner": owner,
                              "line": stmt.line, "constraints": [], "findings": [],
                              "statement": stmt.text}
    if cur.word() == "ADD":
        cur.take()
        groups: list[list[Token]]
        if cur.is_op("(") and cur.word(1) in {"CONSTRAINT", "PRIMARY", "UNIQUE", "CHECK", "FOREIGN"}:
            groups = split_top_level(cur.paren_group())
        else:
            groups = [cur.all[cur.all.index(cur.peek()):]] if not cur.done() else []
            cur.i = len(cur.sig)
        for group in groups:
            c = Cursor(group)
            item = parse_constraint(c, column=None, line=stmt.line, origin="ALTER TABLE")
            if item is None or not c.done():
                result["findings"].append(finding("SCH027", obj=name, line=stmt.line,
                                                  detail=render(group).strip()[:160]))
            else:
                result["constraints"].append(item)
        if not cur.done():
            result["findings"].append(finding("SCH027", obj=name, line=stmt.line,
                                              detail=" ".join(t.text for t in cur.rest())[:160]))
    else:
        result["findings"].append(finding("SCH027", obj=name, line=stmt.line,
                                          detail=" ".join(t.text for t in cur.rest())[:160]))
    return result


def parse_create_index(stmt: Statement) -> dict[str, Any]:
    cur = Cursor(stmt.tokens)
    cur.take()  # CREATE
    unique = bitmap = False
    while cur.word() in {"UNIQUE", "BITMAP", "MULTIVALUE"}:
        w = cur.take().upper
        unique |= w == "UNIQUE"
        bitmap |= w == "BITMAP"
    cur.take()  # INDEX
    owner, name = _read_name(cur)
    index: dict[str, Any] = {"kind": "INDEX", "name": name, "owner": owner, "line": stmt.line,
                             "unique": unique, "bitmap": bitmap, "elements": [], "findings": [],
                             "statement": stmt.text}
    if cur.word() != "ON":
        index["blocked"] = "Index header not understood."
        index["findings"].append(finding("SCH023", obj=name, line=stmt.line, detail="header"))
        return index
    cur.take()
    if cur.word() == "CLUSTER":
        index["blocked"] = "Cluster index is not supported."
        index["findings"].append(finding("SCH023", obj=name, line=stmt.line, detail="CLUSTER"))
        return index
    _, table = _read_name(cur)
    index["table"] = table
    if cur.is_op("("):
        for part in split_top_level(cur.paren_group()):
            sig = significant(part)
            order = ""
            if sig and sig[-1].kind == "IDENT" and sig[-1].upper in {"ASC", "DESC"}:
                order = sig[-1].upper
                part = part[:part.index(sig[-1])]
                sig = sig[:-1]
            if len(sig) == 1 and sig[0].kind in {"IDENT", "QIDENT"}:
                index["elements"].append({"column": identifier_name(sig[0]), "order": order})
            else:
                index["elements"].append({"expressionTokens": part,
                                          "expression": render(part).strip(), "order": order})
    else:
        index["blocked"] = "Index without column list."
        index["findings"].append(finding("SCH023", obj=name, line=stmt.line, detail="no column list"))
    rest = cur.rest()
    words = [t.upper for t in rest if t.kind == "IDENT"]
    if any(w in {"LOCAL", "GLOBAL", "INDEXTYPE", "PARTITION"} for w in words):
        index["blocked"] = "Partitioned/domain index requires target design."
        index["findings"].append(finding("SCH023", obj=name, line=stmt.line, detail=" ".join(words)[:120]))
    elif rest:
        index["findings"].append(finding("SCH019", obj=name, line=stmt.line,
                                         detail=" ".join(t.text for t in rest)[:200]))
    if bitmap:
        index["findings"].append(finding("SCH025", obj=name, line=stmt.line))
    return index


def parse_comment(stmt: Statement) -> dict[str, Any]:
    cur = Cursor(stmt.tokens)
    cur.take()  # COMMENT
    cur.take()  # ON
    target_kind = cur.take().upper
    owner, first = _read_name(cur)
    column = None
    if target_kind == "COLUMN":
        if cur.is_op("."):
            cur.take()
            column = identifier_name(cur.take())
        else:  # read_name consumed table.column
            owner, first, column = None, owner, first
    text = None
    if cur.word() == "IS" and cur.peek(1) is not None and cur.peek(1).kind == "STRING":
        text = string_value(cur.peek(1))
    return {"kind": "COMMENT", "targetKind": target_kind, "table": first, "column": column,
            "text": text, "line": stmt.line}


def parse_sequence(stmt: Statement) -> dict[str, Any]:
    cur = Cursor(stmt.tokens)
    while cur.word() != "SEQUENCE":
        cur.take()
    cur.take()
    owner, name = _read_name(cur)
    opts, dropped, manual = parse_identity_options(cur.all[cur.all.index(cur.peek()):] if not cur.done() else [])
    seq = {"kind": "SEQUENCE", "name": name, "owner": owner, "line": stmt.line, "options": opts,
           "findings": [finding("SCH030", obj=name, line=stmt.line)]}
    if dropped:
        seq["findings"].append(finding("SCH007", obj=name, line=stmt.line, detail=", ".join(dropped)))
    if manual:
        seq["findings"].append(finding("SCH008", obj=name, line=stmt.line, detail=", ".join(manual)))
        seq["blocked"] = "Sequence option without PostgreSQL equivalent."
    return seq
