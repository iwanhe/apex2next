def parse_identity_options(tokens: list[Token]) -> tuple[dict[str, Any], list[str], list[str]]:
    """Parse identity/sequence options. Returns (options, dropped, manual)."""
    sig = [t for t in significant(tokens) if not (t.kind == "OP" and t.text in "(),")]
    opts: dict[str, Any] = {}
    dropped: list[str] = []
    manual: list[str] = []
    i = 0

    def number(j: int) -> int | None:
        if j < len(sig) and sig[j].kind == "NUMBER" and re.fullmatch(r"\d+", sig[j].text):
            return int(sig[j].text)
        if j + 1 < len(sig) and sig[j].text == "-" and sig[j + 1].kind == "NUMBER":
            return -int(sig[j + 1].text)
        return None

    def width(j: int) -> int:
        return 2 if j < len(sig) and sig[j].text == "-" else 1

    while i < len(sig):
        w = sig[i].upper
        if w == "START" and i + 1 < len(sig) and sig[i + 1].upper == "WITH":
            if i + 2 < len(sig) and sig[i + 2].upper == "LIMIT":
                manual.append("START WITH LIMIT VALUE")
                i += 4
                continue
            value = number(i + 2)
            if value is None:
                manual.append("START WITH <expression>")
                i += 3
                continue
            opts["start"] = value
            i += 2 + width(i + 2)
        elif w == "INCREMENT" and i + 1 < len(sig) and sig[i + 1].upper == "BY":
            value = number(i + 2)
            if value is None:
                manual.append("INCREMENT BY <expression>")
                i += 3
                continue
            opts["increment"] = value
            i += 2 + width(i + 2)
        elif w in {"MAXVALUE", "MINVALUE"}:
            value = number(i + 1)
            if value is None:
                manual.append(w)
                i += 1
                continue
            opts[w.lower()] = value
            i += 1 + width(i + 1)
        elif w == "CACHE":
            value = number(i + 1)
            opts["cache"] = value if value is not None else 1
            i += 2 if value is not None else 1
        elif w == "NOCACHE":
            opts["cache"] = 1
            i += 1
        elif w == "CYCLE":
            opts["cycle"] = True
            i += 1
        elif w in {"NOCYCLE", "NOMAXVALUE", "NOMINVALUE", "ORDER", "NOORDER", "NOKEEP",
                   "NOSCALE", "GLOBAL", "NOSHARD"}:
            dropped.append(w)
            i += 1
        elif w in {"KEEP", "SCALE", "EXTEND", "NOEXTEND", "SESSION", "SHARD"}:
            manual.append(w)
            i += 1
        else:
            manual.append(sig[i].text)
            i += 1
    return opts, dropped, manual


def identity_clause(opts: dict[str, Any], target_type: str) -> tuple[str, list[str]]:
    limit = {"smallint": 32767, "integer": 2147483647, "bigint": BIGINT_MAX}.get(target_type, BIGINT_MAX)
    parts: list[str] = []
    notes: list[str] = []
    if "start" in opts:
        parts.append(f"START WITH {opts['start']}")
    if "increment" in opts:
        parts.append(f"INCREMENT BY {opts['increment']}")
    if "minvalue" in opts:
        parts.append(f"MINVALUE {opts['minvalue']}")
    if "maxvalue" in opts:
        if opts["maxvalue"] > limit:
            notes.append(f"MAXVALUE {opts['maxvalue']} exceeds {target_type}; type maximum applies")
        else:
            parts.append(f"MAXVALUE {opts['maxvalue']}")
    if opts.get("cache", 1) > 1:
        parts.append(f"CACHE {opts['cache']}")
    if opts.get("cycle"):
        parts.append("CYCLE")
    return (" (" + " ".join(parts) + ")") if parts else "", notes


# --------------------------------------------------------------------------- constraints


def _consume_state(cur: Cursor, item: dict[str, Any]) -> None:
    """Consume constraint state clauses after a constraint body."""
    while not cur.done():
        w = cur.word()
        if w == "ENABLE":
            cur.take()
        elif w == "DISABLE":
            cur.take()
            item["enabled"] = False
        elif w == "VALIDATE":
            cur.take()
        elif w == "NOVALIDATE":
            cur.take()
            item["validated"] = False
        elif w in {"RELY", "NORELY"}:
            cur.take()
        elif w == "DEFERRABLE":
            cur.take()
            item["deferrable"] = True
        elif w == "NOT" and cur.word(1) == "DEFERRABLE":
            cur.i += 2
        elif w == "INITIALLY" and cur.word(1) in {"IMMEDIATE", "DEFERRED"}:
            item["initiallyDeferred"] = cur.word(1) == "DEFERRED"
            cur.i += 2
        elif w == "USING" and cur.word(1) == "INDEX":
            cur.i += 2
            item["usingIndex"] = True
            if cur.is_op("("):
                cur.paren_group()
            else:
                while not cur.done() and cur.word() not in {"ENABLE", "DISABLE", "CONSTRAINT",
                                                            "NOT", "PRIMARY", "UNIQUE", "CHECK",
                                                            "REFERENCES", "NOVALIDATE",
                                                            "VALIDATE"}:
                    if cur.is_op("("):
                        cur.paren_group()
                    else:
                        cur.take()
        elif w == "EXCEPTIONS" and cur.word(1) == "INTO":
            cur.i += 2
            _read_name(cur)
            item.setdefault("manual", []).append("EXCEPTIONS INTO")
        else:
            break


def parse_constraint(cur: Cursor, *, column: str | None, line: int,
                     origin: str) -> dict[str, Any] | None:
    """Parse one inline/out-of-line constraint at the cursor (or return None)."""
    name: str | None = None
    if cur.word() == "CONSTRAINT":
        cur.take()
        name = identifier_name(cur.take())
    item: dict[str, Any] = {"name": name, "line": line, "origin": origin, "enabled": True,
                            "validated": True}
    w = cur.word()
    if w == "PRIMARY" and cur.word(1) == "KEY":
        cur.i += 2
        item["kind"] = "PRIMARY KEY"
        item["columns"] = _column_list(cur.paren_group()) if cur.is_op("(") else [column]
    elif w == "UNIQUE":
        cur.take()
        item["kind"] = "UNIQUE"
        item["columns"] = _column_list(cur.paren_group()) if cur.is_op("(") else [column]
    elif w == "CHECK":
        cur.take()
        item["kind"] = "CHECK"
        item["expressionTokens"] = cur.paren_group()
        item["expression"] = render(item["expressionTokens"]).strip()
        item["columns"] = [column] if column else []
    elif w == "NOT" and cur.word(1) == "NULL":
        cur.i += 2
        item["kind"] = "NOT NULL"
        item["columns"] = [column]
    elif w == "NULL":
        cur.take()
        item["kind"] = "NULL"
        item["columns"] = [column]
    elif w in {"FOREIGN", "REFERENCES"}:
        if w == "FOREIGN":
            if cur.word(1) != "KEY":
                return None
            cur.i += 2
            item["columns"] = _column_list(cur.paren_group())
        else:
            item["columns"] = [column]
        if cur.word() != "REFERENCES":
            return None
        cur.take()
        owner, target = _read_name(cur)
        item["kind"] = "FOREIGN KEY"
        item["targetOwner"] = owner
        item["target"] = target
        item["targetColumns"] = _column_list(cur.paren_group()) if cur.is_op("(") else []
        if cur.word() == "ON" and cur.word(1) == "DELETE":
            cur.i += 2
            if cur.word() == "CASCADE":
                cur.take()
                item["onDelete"] = "CASCADE"
            elif cur.word() == "SET" and cur.word(1) == "NULL":
                cur.i += 2
                item["onDelete"] = "SET NULL"
            else:
                item.setdefault("manual", []).append("ON DELETE " + (cur.word() or ""))
    else:
        return None
    _consume_state(cur, item)
    return item


