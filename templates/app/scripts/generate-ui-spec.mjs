#!/usr/bin/env node
// WP9.5: turns ui/apex-page-inventory.json (derived from the authoritative APEX SQL export, see D-003)
// into a typed UI specification used by both the API and the web app. Labels, messages, LOVs,
// navigation, report columns and form item properties are therefore copied, not retyped.
// Usage: node scripts/generate-ui-spec.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const inventory = JSON.parse(readFileSync(join(root, 'ui', 'apex-page-inventory.json'), 'utf8'));
const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());

const pages = {};
for (const page of inventory.pages) {
  const components = {};
  for (const c of page.components) {
    const kind = camel(c.kind.toLowerCase());
    components[kind] ??= {};
    const props = {};
    for (const [k, v] of Object.entries(c.props)) props[camel(k)] = v;
    components[kind][c.name] = { key: c.key, ...props };
  }
  pages[page.id] = { id: page.id, name: page.name, title: page.title, alias: page.alias ?? null, mode: page.mode,
    scheme: page.scheme ?? null, ...components };
}
const spec = {
  inventorySha256: inventory.sha256,
  application: inventory.application,
  authorizations: inventory.authorizations.map(({ name, errorMessage }) => ({ name, errorMessage })),
  lovs: Object.fromEntries(inventory.lovs.map((l) => [l.name, { location: l.location, query: l.query, values: l.values }])),
  navigation: inventory.navigation,
  navigationBar: inventory.navigationBar,
  breadcrumbs: inventory.breadcrumbs,
  pages,
};
const body = `// GENERATED by scripts/generate-ui-spec.mjs from ui/apex-page-inventory.json. Do not edit.\n`
  + `/* eslint-disable */\nexport const UI_SPEC = ${JSON.stringify(spec, null, 2)} as const;\n`
  + `export type UiSpec = typeof UI_SPEC;\n`;
const targets = [join(root, 'apps', 'api', 'src', 'pages', 'ui-spec.generated.ts'),
  join(root, 'apps', 'web', 'lib', 'ui-spec.generated.ts')];
let stale = false;
for (const target of targets) {
  if (process.argv.includes('--check')) {
    let current = '';
    try { current = readFileSync(target, 'utf8'); } catch { /* missing */ }
    if (current !== body) { console.error(`stale: ${target}`); stale = true; }
  } else {
    writeFileSync(target, body);
  }
}
process.exit(stale ? 1 : 0);
